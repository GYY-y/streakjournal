import Foundation

enum Encouragement {
    private static let thresholds: [(days: Int, messages: [String])] = [
        (365, [
            "一整年的记录已经积累成一本属于你的历史，值得慢慢翻阅。",
            "三百多天的经历，回头看时你会感谢这些认真记录的日子。",
        ]),
        (180, [
            "半年过去了，这些记录见证了你的变化。",
            "一百八十多天的坚持，已经是生活的一部分。",
        ]),
        (100, [
            "一百天的经历，已经成为你个人成长记录的一部分。",
            "第一百天，回头看时已经走了很远的路。",
        ]),
        (60, [
            "两个月的坚持，节奏正在慢慢变成习惯。",
            "六十多天了，记录本身就在替你保存这段时光。",
        ]),
        (30, [
            "你已经积累了一个月的经历，回头看看自己的变化。",
            "一个月的记录，比任何感觉都更真实。",
        ]),
        (14, [
            "两周过去了，继续保持自己的节奏。",
            "十四天的记录已经能看出一些变化了。",
        ]),
        (7, [
            "一周的坚持，值得被认真记录。",
            "第七天，这一周的经历已经是完整的记忆。",
        ]),
        (3, [
            "已经坚持三天，继续保持自己的节奏。",
            "第三天，节奏正在建立。",
        ]),
        (1, [
            "新的开始，从今天认真做好一件事。",
            "第一天，记录从今天开始积累。",
        ]),
    ]

    /// 根据当前坚持天数返回一句鼓励语（随机选取该档位中的一句）
    static func message(days: Int) -> String {
        for t in thresholds where days >= t.days {
            return t.messages.randomElement() ?? ""
        }
        return "每一次开始都值得认真对待。"
    }
}
